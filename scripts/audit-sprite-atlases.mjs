import fs from 'node:fs/promises';
import {resolve,basename,relative} from 'node:path';
import {createHash} from 'node:crypto';
const root=resolve('docs'),dir=resolve(root,'media/assets/spritesheets'),output=resolve(process.env.SPRITE_AUDIT_OUTPUT||'outputs/sprite-atlas-audit');
await fs.mkdir(output,{recursive:true});
const files=await fs.readdir(resolve(dir,'json')),json=new Map();
for(const file of files.filter(f=>f.endsWith('.json')))json.set(file,JSON.parse(await fs.readFile(resolve(dir,'json',file),'utf8')));
const definitions=[];
const pagesInManifest=new Set([...json.values()].flatMap(j=>j.pages?.map(p=>p.json)||[]));
for(const [file,data] of json){
  if(pagesInManifest.has(file))continue;
  const pages=data.pages?.map(p=>({file:p.json,data:json.get(p.json)}))||[{file,data}];
  const frames=data.pages?data.frames.map(f=>({...pages[f.page]?.data?.frames[f.frame],page:f.page,duration:f.duration,id:f.frame}))
    :(data.animations?.[data.meta.animation.name]||Object.keys(data.frames)).map(id=>({...data.frames[id],id,page:0}));
  const animation=data.animation||data.meta?.animation,errors=[];
  const width=frames[0]?.sourceSize?.w,height=frames[0]?.sourceSize?.h;
  for(const [i,page] of pages.entries()){
    if(!page.data){errors.push(`Missing JSON page ${i}`);continue;}
    const image=basename(page.data.meta.image),png=await fs.readFile(resolve(dir,'png',image)).catch(()=>null);
    if(!png){errors.push(`Missing PNG ${image}`);continue;}
    if(png.readUInt32BE(16)!==page.data.meta.size.w||png.readUInt32BE(20)!==page.data.meta.size.h)errors.push(`PNG size differs: ${image}`);
  }
  for(const f of frames){const page=pages[f.page]?.data,r=f.frame,s=f.spriteSourceSize;
    if(!r||!s||!page||!Number.isFinite(f.duration)||f.duration<0||f.rotated||f.sourceSize?.w!==width||f.sourceSize?.h!==height||r.x<0||r.y<0||r.x+r.w>page.meta.size.w||r.y+r.h>page.meta.size.h||s.x<0||s.y<0||s.x+s.w>width||s.y+s.h>height)errors.push(`Invalid frame ${f.id}`);
  }
  const duration=frames.reduce((n,f)=>n+f.duration,0);
  if(frames.length!==animation.frameCount||duration!==animation.durationMs)errors.push('Frame count or duration mismatch');
  definitions.push({name:animation.name,file,pages:pages.map(p=>({json:p.file,image:basename(p.data.meta.image)})),width,height,frames:frames.length,duration,browserDuration:frames.reduce((n,f)=>n+(f.duration<=10?100:f.duration),0),normalizedDelays:frames.filter(f=>f.duration<=10).length,sourceLoop:animation.sourceGifLoopValue,errors});
}
const walk=async dir=>(await Promise.all((await fs.readdir(dir,{withFileTypes:true})).map(e=>e.isDirectory()?walk(resolve(dir,e.name)):[resolve(dir,e.name)]))).flat();
const sources=(await walk(resolve(root,'js'))).concat(await walk(resolve(root,'css')),(await fs.readdir(root)).filter(f=>f.endsWith('.html')).map(f=>resolve(root,f)));
const sourceTexts=await Promise.all(sources.map(async file=>({file:relative(root,file).replaceAll('\\','/'),text:(await fs.readFile(file,'utf8')).toLowerCase()})));
const gifs=(await walk(resolve(root,'media'))).filter(f=>f.toLowerCase().endsWith('.gif'));
const used=[],unused=[];
for(const gif of gifs){const name=basename(gif),stem=name.slice(0,-4).toLowerCase();
  const references=sourceTexts.filter(s=>s.text.includes(name.toLowerCase())||s.text.includes('media/'+relative(resolve(root,'media'),gif).replaceAll('\\','/').slice(0,-4).toLowerCase())).map(s=>s.file);
  if(/^blood-impact-[1-6]$/i.test(stem))references.push('js/rendering/animations.js (dynamic 1–6)');
  const atlas=definitions.find(d=>d.name.toLowerCase()===stem);
  const record={gif:relative(root,gif).replaceAll('\\','/'),atlas:atlas?.file||null,references:[...new Set(references)],preloadOnly:references.every(p=>p==='js/data/loaderList.js'),debugOnly:references.every(p=>p==='js/data/loaderList.js'||p==='js/debug/vfxCalibrator.js')};
  (references.length?used:unused).push(record);
}
const missing=used.filter(g=>!g.atlas),unusedAtlases=definitions.filter(a=>!used.some(g=>g.atlas===a.file));
const report={animations:definitions.length,pages:definitions.reduce((n,d)=>n+d.pages.length,0),frames:definitions.reduce((n,d)=>n+d.frames,0),definitions,used,missing,unusedAtlases:unusedAtlases.map(d=>d.name),unusedGifs:unused.map(g=>g.gif)};
await fs.writeFile(resolve(output,'atlas-audit.json'),JSON.stringify(report,null,2));
const catalog=Object.fromEntries(definitions.map(d=>[d.name.toLowerCase(),{json:`./media/assets/spritesheets/json/${d.file}`,width:d.width,height:d.height}]));
const catalogPath=resolve(root,'js/data/spriteAtlasCatalog.js');
const catalogSource='// Generated by scripts/audit-sprite-atlases.mjs --catalog. Atlas pages stay shared.\nexport const SPRITE_ATLASES = '+JSON.stringify(catalog,null,2)+';\n';
if(process.argv.includes('--catalog'))await fs.writeFile(catalogPath,catalogSource);
else if(await fs.readFile(catalogPath,'utf8')!==catalogSource)throw Error('Rebuild the sprite catalog: node scripts/audit-sprite-atlases.mjs --catalog');
if(process.argv.includes('--snapshot')){
  const entries=[];
  for(const file of [...await walk(root),...await walk(resolve('scripts'))])entries.push({path:file,sha256:createHash('sha256').update(await fs.readFile(file)).digest('hex')});
  await fs.writeFile(resolve(output,'before-manifest.json'),JSON.stringify(entries,null,2));
  await fs.cp(root,resolve(output,'before/docs'),{recursive:true});
}
console.log(JSON.stringify({animations:report.animations,pages:report.pages,frames:report.frames,errors:definitions.filter(d=>d.errors.length).map(d=>({name:d.name,errors:d.errors})),missing:missing.map(g=>g.gif),unusedAtlases:report.unusedAtlases},null,2));
if(definitions.some(d=>d.errors.length))process.exitCode=1;
