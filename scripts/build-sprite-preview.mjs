import fs from 'node:fs/promises';
import {resolve} from 'node:path';
// index-16 also opens directly with file://. Embed JSON and the same reader in
// a classic-script bundle; native PNG loading works without fetch/CORS there.
const json={};
for(const name of await fs.readdir('docs/media/assets/spritesheets/json'))if(name.endsWith('.json'))
  json[name]=JSON.parse(await fs.readFile(resolve('docs/media/assets/spritesheets/json',name),'utf8'));
const catalog=(await fs.readFile('docs/js/data/spriteAtlasCatalog.js','utf8')).replace('export const','const');
let reader=(await fs.readFile('docs/js/rendering/spriteAnimation.js','utf8')).replace(/^import .*;\r?\n/gm,'').replace(/\bexport (?=(?:async )?function)/g,'');
reader=reader.replace('const readJSON = async (url, signal) => {','const readJSON = async (url, signal) => {\n  const embedded = PREVIEW_JSON[new URL(url, document.baseURI).pathname.split("/").pop()];\n  if (embedded) return structuredClone(embedded);');
const bundle='// Generated by scripts/build-sprite-preview.mjs. Do not edit.\n(()=>{\nconst clockNow=()=>Date.now(),isCombatPaused=()=>false,waitForCombatResume=()=>Promise.resolve();\nconst PREVIEW_JSON='+JSON.stringify(json)+';\n'+catalog+'\n'+reader+'\nwindow.SpritePreview={createSpriteImage,inspectSpriteAnimations};\n})();\n';
const path='docs/js/debug/spritePreviewBundle.js';
if(process.argv.includes('--check')){
  if(await fs.readFile(path,'utf8')!==bundle)throw Error('Rebuild the sprite preview bundle');
}else await fs.writeFile(path,bundle);
console.log('Sprite preview bundle matches shared renderer and atlas metadata.');
