eq(hybrid.burnSeconds,2.75,'Fractional burn duration');eq(hybrid.lifesteal,2.75,'Fractional lifesteal');
eq(hybrid.explosion,0,'No hybrid explosion');eq(hybrid.precision,0,'No hybrid precision');
const kinetic=D.criticalNaturePlan(nature(['red','red','red','yellow']),100,60);
eq(kinetic.immediate.physical,45,'Kinetic proportional physical');eq(kinetic.immediate.piercingDamage,15,'Kinetic proportional piercing');eq(kinetic.lifesteal,4.5,'Kinetic proportional lifesteal');
const spectral=D.criticalNaturePlan(nature(['blue','blue','blue','yellow']),100,60);
eq(spectral.burn,45,'Spectral proportional magical burn');eq(spectral.immediate.piercingDamage,15,'Spectral immediate piercing');eq(spectral.burnSeconds,4.5,'Spectral duration');eq(spectral.lifesteal,0,'No physical share means no critical lifesteal');
const magic=D.criticalNaturePlan(nature(['blue']),20,50);
