const H = await import('../docs/js/entities/healthCapacity.js');
const B = await import('../docs/js/board/model.js');
let checks = 0;
const eq = (actual, expected, label) => { assert.ok(Math.abs(actual-expected)<1e-8, `${label}: ${actual} != ${expected}`); checks++; };
for (const [physical, magical, expected] of [[0,200,.4],[20,100,.6],[50,100,.7],[50,50,1],[100,50,1.4],[100,20,1+96/180],[200,0,1.8],[500,0,2]]) {
  eq(D.piercingResistanceMultiplier(physical,magical),expected,'Original piercing differential');
  const target={stats:{physicalResistance:physical,magicalResistance:magical}};
  eq(E.calculateResistances(target,{piercingDamage:100}).reducedpiercingDamage,expected*100,'Production resistance pipeline');
}
