import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import vm from 'node:vm';

const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const output=resolve('outputs/index14-new-old');await mkdir(output,{recursive:true});
const html=await readFile('docs/index-14.html','utf8');
for(const [,script] of html.matchAll(/<script>([\s\S]*?)<\/script>/g))new vm.Script(script);
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'msedge',headless:true});
const checks=[];
const check=(condition,label)=>{assert.ok(condition,label);checks.push(label);};
const near=(actual,expected,label)=>check(Math.abs(actual-expected)<1e-7,`${label}: ${actual}`);
try{
  const page=await browser.newPage({viewport:{width:1360,height:1000}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(resolve('docs/index-14.html')).href);
  const entity=page.locator('.entity').first(),tabs=entity.locator('[data-mode]');
  assert.deepEqual(await tabs.allTextContents(),['New','Old']);checks.push('Exactly two modes: New and Old');
  check(await entity.locator('[data-mode="maj"]').getAttribute('aria-selected')==='true','New selected by default');
  check(await page.locator('#common-balancing').isHidden(),'Removed concept controls are hidden');
  await entity.locator('[data-catalog="umbras"] > summary').click();
  await entity.locator('[data-add="umbra-resilience"]').click();
  const points=entity.locator('input[data-group="umbras"][data-key="resilience"]');
  const force=entity.locator('input[data-group="attributes"][data-key="strength"]');
  await points.fill('50');await force.fill('50');
  await entity.getByRole('button',{name:'Voir la courbe de Résilience totale',exact:true}).click();
  const chart=entity.locator('[data-ui="curve-chart"]');
  check(await entity.locator('[data-ui="curve-effect"]').inputValue()==='resilienceTotal','Total passive opens from its summary');
  check(await entity.locator('[data-ui="curve-view"]').inputValue()==='total','Passive chart shows percentages');
  check(await entity.locator('[data-ui="curve-view"] option[value="ratio"]').evaluate(option=>option.disabled),'Passive cannot display a misleading Umbra multiplier');
  near(Number(await chart.getAttribute('data-current')),4.06780980420414,'Real game passive at 50 Resilience / 50 Force');
  const forceText=await entity.locator('[data-ui="curve-attribute"]').innerText();
  check(forceText.includes('1,5236')&&forceText.includes('0,3809'),'Force progression and pre-conversion coefficient are distinguished');
  await entity.locator('input[data-group="attributes"][data-key="agility"]').fill('150');
  near(Number(await chart.getAttribute('data-current')),4.06780980420414,'Agility does not change total Resilience');
  await force.fill('150');
  near(Number(await chart.getAttribute('data-current')),4.772961816305469,'Force input updates the curve');
  await entity.locator('[data-mode="current"]').click();
  check(await entity.locator('[data-mode="current"]').getAttribute('aria-selected')==='true','Old selects historical formulas');
  check(await points.inputValue()==='50'&&await force.inputValue()==='150','Inputs preserved in Old');
  const oldExpected=await page.evaluate(()=>{const s=umbraLab.initialState();s.mode='current';s.umbras.resilience=50;s.attributes.strength=150;s.attributes.agility=150;return umbraLab.calculate(s).results.resilienceTotal.total;});
  near(Number(await chart.getAttribute('data-current')),oldExpected,'Old chart uses the historical engine');
  await entity.locator('[data-mode="maj"]').click();
  near(Number(await chart.getAttribute('data-current')),4.772961816305469,'Switching back restores the live calculation');
  await points.fill('100');
  const nextExpected=await page.evaluate(()=>umbraProgression.resilienceCancelDetails(100,150).percent);
  near(Number(await chart.getAttribute('data-current')),nextExpected,'Resilience input updates the curve');
  await points.fill('0');near(Number(await chart.getAttribute('data-current')),0,'Force alone generates no passive');
  await points.fill('50');await force.fill('50');
  const panel=chart.locator('..');await panel.screenshot({path:resolve(output,'resilience-total-new.png')});
  await page.selectOption('#conversion-stat','resilienceTotal');
  await page.fill('#conversion-points','50');await page.fill('#conversion-agility','50');
  const conversion=page.locator('#conversion-chart');
  near(Number(await conversion.getAttribute('data-percent')),4.06780980420414,'Independent conversion chart uses the same passive');
  near(Number(await page.locator('#conversion-shape').inputValue()),98,'Default passive spread is 98');
  await page.fill('#conversion-points','100');
  near(Number(await conversion.getAttribute('data-percent')),6.997104067358739,'Selected curve: 100 Resilience / 50 Force');
  await page.fill('#conversion-points','50');
  check((await page.locator('#conversion-agility-field').innerText()).includes('Force'),'Passive conversion is labelled Force');
  check((await page.locator('#conversion-formula').innerText()).includes('Résilience totale'),'Conversion describes the selected passive');
  await page.fill('#conversion-percent','20');
  const convertedPoints=Number(await page.locator('#conversion-points').inputValue());
  const reconstructed=await page.evaluate(p=>umbraProgression.resilienceCancelDetails(p,50).percent,convertedPoints);
  near(reconstructed,20,'Percentage input finds matching Resilience points');
  await page.fill('#conversion-limit','80');
  near(Number(await conversion.getAttribute('data-limit')),80,'Effect limit can be explored');
  near(Number(await chart.getAttribute('data-current')),4.06780980420414,'Conversion experiments do not modify game or entity settings');
  await page.locator('#stat-conversion').screenshot({path:resolve(output,'resilience-total-conversion.png')});
  await entity.locator('[data-mode="maj"]').focus();await page.keyboard.press('ArrowRight');
  check(await entity.locator('[data-mode="current"]').getAttribute('aria-selected')==='true','Keyboard navigation reaches Old');
  await page.keyboard.press('ArrowRight');
  check(await entity.locator('[data-mode="maj"]').getAttribute('aria-selected')==='true','Keyboard navigation wraps directly to New');
  await page.locator('#add-entity').click();
  check(await page.locator('.entity').nth(1).locator('[data-mode="maj"]').getAttribute('aria-selected')==='true','Additional entity starts in New');
  await entity.locator('[data-ui="clear"]').click();
  check(await entity.locator('[data-mode="maj"]').getAttribute('aria-selected')==='true','Clearing preserves selected mode');
  check(await entity.locator('.stat-total').count()===0,'Clearing removes all totals and chart shortcuts');
  check(!/\bConcept\b|\bMaj\b|\bActuel\b/.test(await page.locator('body').innerText()),'Visible page only names New and Old');
  for(const size of [{width:390,height:844},{width:1360,height:1000}]){
    await page.setViewportSize(size);
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Page stays within viewport');
  }
  assert.deepEqual(errors,[]);checks.push('No browser errors');
  await writeFile(resolve(output,'browser-report.json'),JSON.stringify({checks,errors},null,2));
  console.log(`PASS: ${checks.length} Index 14 mode/passive curve checks.`);
}finally{await browser.close();}
